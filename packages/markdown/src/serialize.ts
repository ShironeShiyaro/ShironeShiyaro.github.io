import { stringify as stringifyYaml } from 'yaml';
import type { MarkdownError } from './errors.ts';
import { getShanghaiTimestamp, isValidIsoDate, type ShanghaiTimestamp } from './date.ts';
import {
  BODY_MAX_BYTES,
  sanitizeTitleForFileName,
  utf8ByteLength,
  validateTitle,
} from './title.ts';

/**
 * The public Blog content root. The writer may only create files below it.
 */
export const POST_CONTENT_ROOT = 'content/blog';

/**
 * The body is preserved verbatim except for newline normalisation. CRLF and
 * lone CR become LF; a missing final newline is added. Nothing is trimmed,
 * escaped, re-indented or re-wrapped.
 */
export function normalizeBody(body: string): string {
  const normalized = body.replace(/\r\n?/g, '\n');
  return normalized.endsWith('\n') ? normalized : `${normalized}\n`;
}

export interface SerializePostInput {
  title: string;
  body: string;
  /** Asia/Shanghai calendar date, `YYYY-MM-DD`. */
  date: string;
}

export interface SerializedPost {
  /** Trimmed original title; this is the literal H1 text. */
  title: string;
  /** Normalised body (CRLF -> LF, final newline guaranteed). */
  body: string;
  date: string;
  safeTitle: string;
  /** YAML front matter without the `---` delimiters. */
  frontMatter: string;
  /** Everything the reader sees: H1, date, separator, body. */
  visibleMarkdown: string;
  /** Front matter + visible Markdown. */
  markdown: string;
}

export type SerializePostResult =
  | { ok: true; post: SerializedPost }
  | { ok: false; errors: MarkdownError[] };

function validateBody(rawBody: unknown): { body: string; errors: MarkdownError[] } {
  const errors: MarkdownError[] = [];
  if (typeof rawBody !== 'string' || rawBody.trim() === '') {
    errors.push({
      code: 'body_required',
      field: 'body',
      message: 'Enter the post body before publishing.',
    });
    return { body: '', errors };
  }

  // The 256 KiB limit applies to the author's body after newline
  // normalisation, before the serializer adds its required final newline.
  const normalized = rawBody.replace(/\r\n?/g, '\n');
  if (utf8ByteLength(normalized) > BODY_MAX_BYTES) {
    errors.push({
      code: 'body_too_large',
      field: 'body',
      message: `The post body must be ${BODY_MAX_BYTES / 1024} KiB or smaller.`,
    });
  }
  return { body: normalizeBody(rawBody), errors };
}

function validateDate(rawDate: unknown): MarkdownError[] {
  if (isValidIsoDate(rawDate)) {
    return [];
  }
  return [
    {
      code: 'date_invalid',
      field: 'date',
      message: 'The publication date is unavailable or invalid. Reload the page and try again.',
    },
  ];
}

/**
 * The one New! Markdown serializer.
 *
 * Visible output is exactly:
 *
 * ```md
 * # <title>
 *
 * <date>
 *
 * ---
 *
 * <body>
 * ```
 *
 * Front matter contains only `title` and `date`, generated by the YAML
 * serializer so a title with `:`, quotes, `*`, `<` or `#` cannot inject
 * additional fields.
 */
export function serializePost(input: SerializePostInput): SerializePostResult {
  const titleValidation = validateTitle(input?.title);
  const bodyValidation = validateBody(input?.body);
  const errors = [...titleValidation.errors, ...bodyValidation.errors, ...validateDate(input?.date)];

  if (errors.length > 0) {
    return { ok: false, errors };
  }

  const title = titleValidation.title;
  const body = bodyValidation.body;
  const date = input.date;
  const frontMatter = stringifyYaml({ title, date }, { lineWidth: 0 });
  const visibleMarkdown = `# ${title}\n\n${date}\n\n---\n\n${body}`;
  return {
    ok: true,
    post: {
      title,
      body,
      date,
      safeTitle: titleValidation.safeTitle,
      frontMatter,
      visibleMarkdown,
      markdown: `---\n${frontMatter}---\n\n${visibleMarkdown}`,
    },
  };
}

/**
 * File name below `content/blog/YYYY/`:
 * `<safe title>-YYYY-MM-DD-HH-mm-ss.md`.
 */
export function buildPostFileName(
  title: string,
  timestamp: Pick<ShanghaiTimestamp, 'date' | 'time'>,
): string {
  return `${sanitizeTitleForFileName(title)}-${timestamp.date}-${timestamp.time}.md`;
}

/** Repository-relative path for a new post; never accepts a caller-chosen root. */
export function buildPostPath(
  title: string,
  timestamp: Pick<ShanghaiTimestamp, 'date' | 'time'>,
): string {
  const year = timestamp.date.slice(0, 4);
  return `${POST_CONTENT_ROOT}/${year}/${buildPostFileName(title, timestamp)}`;
}

export interface PublishPlan {
  post: SerializedPost;
  fileName: string;
  path: string;
  timestamp: ShanghaiTimestamp;
}

export type PublishPlanResult = { ok: true; plan: PublishPlan } | { ok: false; errors: MarkdownError[] };

/**
 * Serialises a post for a concrete publish instant. The timestamp is
 * server-derived (`Asia/Shanghai`); this helper keeps the date in the visible
 * Markdown and in the file name in lockstep.
 */
export function planPublish(
  input: { title: string; body: string },
  instant: Date | number,
): PublishPlanResult {
  const timestamp = getShanghaiTimestamp(instant);
  const serialized = serializePost({ ...input, date: timestamp.date });
  if (!serialized.ok) {
    return serialized;
  }
  return {
    ok: true,
    plan: {
      post: serialized.post,
      fileName: buildPostFileName(serialized.post.title, timestamp),
      path: buildPostPath(serialized.post.title, timestamp),
      timestamp,
    },
  };
}
